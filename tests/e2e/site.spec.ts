test('light and dark text meet WCAG AA contrast', async ({ page }) => {
  await page.goto('/#settings')
  for (const theme of ['浅色','深色']) {
    await page.getByRole('button',{name:theme,exact:true}).last().click()
    const ratios=await page.evaluate(() => {
      const root=getComputedStyle(document.documentElement)
      const rgb=(color:string) => { const el=document.createElement('div');el.style.color=color;document.body.append(el);const v=getComputedStyle(el).color.match(/[\d.]+/g)!.map(Number).slice(0,3);el.remove();return v }
      const lum=(c:number[])=>c.map(n=>n/255).map(n=>n<=.04045?n/12.92:((n+.055)/1.055)**2.4).reduce((n,s,i)=>n+s*[.2126,.7152,.0722][i]!,0)
      const ratio=(a:string,b:string)=>{const x=lum(rgb(a)),y=lum(rgb(b));return (Math.max(x,y)+.05)/(Math.min(x,y)+.05)}
      return ['--surface','--soft','--bg'].flatMap(bg=>['--text','--muted'].map(fg=>ratio(root.getPropertyValue(fg),root.getPropertyValue(bg))))
    })
    for (const ratio of ratios) expect(ratio).toBeGreaterThanOrEqual(4.5)
  }
})
