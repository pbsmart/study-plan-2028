import { test, expect } from '@playwright/test'
const home = '/#learn/1/physics/prepare'
const storageKey = 'xunxu.podcast.v1'
test.beforeEach(async ({ page }) => { await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.goto(home) })

test('full MP3 loads, playback controls work and route changes keep the same audio playing', async ({ page }) => {
  await expect(page.locator('.lesson-podcast')).toContainText('Dylan / Serena')
  await expect(page.locator('.podcast-transcript')).not.toHaveAttribute('open', '')
  await page.getByRole('button', { name: '播放播客', exact: true }).click()
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate(el => (el as HTMLAudioElement).duration)).toBeCloseTo(398.805, 0)
  await expect.poll(() => audio.evaluate(el => (el as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
  await page.getByLabel('播放倍速', { exact: true }).selectOption('1.5')
  expect(await audio.evaluate(el => (el as HTMLAudioElement).playbackRate)).toBe(1.5)
  const seek = page.getByLabel('播客播放进度', { exact: true })
  await seek.fill('100'); await seek.dispatchEvent('input')
  await page.getByRole('button', { name: '前进15秒', exact: true }).click()
  await expect.poll(() => audio.evaluate(el => (el as HTMLAudioElement).currentTime)).toBeGreaterThan(114)
  await page.getByRole('button', { name: '后退15秒', exact: true }).click()
  await expect.poll(() => audio.evaluate(el => (el as HTMLAudioElement).currentTime)).toBeLessThan(105)
  await audio.evaluate(el => { (el as HTMLAudioElement).dataset.identity = 'original' })
  await page.evaluate(() => { location.hash = 'learn/2/physics/prepare' })
  await expect(page.locator('.podcast-mini')).toBeVisible(); await expect(page.locator('.podcast-pending')).toBeVisible()
  await expect(page.locator('audio')).toHaveCount(1); await expect(audio).toHaveAttribute('data-identity', 'original')
  expect(await audio.evaluate(el => (el as HTMLAudioElement).paused)).toBe(false)
  await page.locator('.podcast-mini a').click(); await expect(page.locator('.lesson-podcast')).toBeVisible()
  await expect(page.locator('.podcast-mini')).toHaveCount(0)
  await page.getByRole('button', { name: '暂停播客', exact: true }).click()
  expect(await audio.evaluate(el => (el as HTMLAudioElement).paused)).toBe(true)
})

test('per-lesson breakpoint and rate survive refresh without autoplay; restart begins at zero', async ({ page }) => {
  await page.getByRole('button', { name: '播放播客', exact: true }).click()
  const seek = page.getByLabel('播客播放进度', { exact: true })
  await expect(seek).toBeEnabled(); await seek.fill('123'); await seek.dispatchEvent('input')
  await page.getByLabel('播放倍速', { exact: true }).selectOption('1.25')
  await page.getByRole('button', { name: '暂停播客', exact: true }).click(); await page.reload()
  await expect(page.locator('.podcast-time')).toContainText('2:03')
  expect(await page.locator('audio').evaluate(el => (el as HTMLAudioElement).paused)).toBe(true)
  await page.getByRole('button', { name: '播放播客', exact: true }).click(); await expect(seek).toBeEnabled()
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).currentTime)).toBeGreaterThan(122)
  expect(await page.locator('audio').evaluate(el => (el as HTMLAudioElement).playbackRate)).toBe(1.25)
  await page.getByRole('button', { name: '从头播放', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).currentTime)).toBeLessThan(3)
})

test('real media ending records listened only, with no next lesson or mastery checkoff', async ({ page }) => {
  await page.getByRole('button', { name: '播放播客', exact: true }).click()
  const seek = page.getByLabel('播客播放进度', { exact: true }); await expect(seek).toBeEnabled()
  await seek.fill('398.6'); await seek.dispatchEvent('input')
  await expect(page.locator('.podcast-time')).toContainText('已听完 · 不代表已掌握')
  await expect(page.getByRole('button', { name: '播放播客', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/#learn\/1\/physics\/prepare$/)
  const data = await page.evaluate(key => ({ listening: JSON.parse(localStorage.getItem(key) || '{}'), plan: JSON.parse(localStorage.getItem('xunxu.gaokao.v1') || '{}') }), storageKey)
  expect(data.listening['w1-physics-distance'].listened).toBe(true)
  expect(Object.values(data.plan.weeks || {}).every((week: any) => week.completed.length === 0 && week.sessions.length === 0)).toBe(true)
})

test('failed audio has an honest retry and unavailable lessons offer no fake player', async ({ page }) => {
  await page.route('**/audio/*.mp3', route => route.abort())
  await page.getByRole('button', { name: '播放播客', exact: true }).click()
  await expect(page.locator('.podcast-error')).toBeVisible()
  await page.unroute('**/audio/*.mp3'); await page.getByRole('button', { name: '重试音频', exact: true }).click()
  await expect.poll(() => page.locator('audio').evaluate(el => (el as HTMLAudioElement).currentTime)).toBeGreaterThan(0)
  await page.getByRole('button', { name: '暂停播客', exact: true }).click()
  await page.evaluate(() => { location.hash = 'learn/1/math/prepare' })
  await expect(page.locator('.podcast-pending')).toBeVisible(); await expect(page.locator('.lesson-podcast')).toHaveCount(0)
  await expect(page.locator('.podcast-mini')).toContainText('路程与位移')
})

